const CONTACTS = "requisitionerContacts";

function requireDb(db: any) {
  if (!db) throw new Error("Firebase is not configured. Add your NEXT_PUBLIC_FIREBASE_* variables.");
  return db;
}

function contactId(name: string, email: string) {
  const raw = `${String(name || "").trim().toLowerCase()}|${String(email || "").trim().toLowerCase()}`;
  let hash = 0;
  for (let i = 0; i < raw.length; i += 1) hash = (hash * 31 + raw.charCodeAt(i)) | 0;
  const slug = String(name || "requisitioner")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 70) || "requisitioner";
  return `${slug}-${Math.abs(hash).toString(36)}`;
}

/**
 * Optional one-time Firestore seeder for the bundled requisitioner directory.
 * The normal Email Directory page can use REQUISITIONER_CONTACTS directly,
 * so this is not required just to display the list.
 */
export async function seedRequisitionerDirectoryCloud(
  db: any,
  options?: { createdBy?: string; overwrite?: boolean },
) {
  const firestore = requireDb(db);
  const { doc, setDoc, writeBatch } = await import("firebase/firestore");
  const overwrite = options?.overwrite === true;
  const createdBy = String(options?.createdBy || "system");
  const now = new Date().toISOString();

  for (let i = 0; i < REQUISITIONER_CONTACTS.length; i += 400) {
    const batch = writeBatch(firestore);
    REQUISITIONER_CONTACTS.slice(i, i + 400).forEach((contact) => {
      const id = contactId(contact.name, contact.email);
      const payload = {
        id,
        name: contact.name,
        email: contact.email.toLowerCase(),
        roles: ["requisitioner"],
        department: contact.department || "",
        notes: "Possible Requisitioner Directory",
        createdAt: now,
        updatedAt: now,
        createdBy,
      };
      batch.set(
        doc(firestore, CONTACTS, id),
        payload,
        overwrite ? { merge: false } : { merge: true },
      );
    });
    await batch.commit();
  }

  return { ok: true, count: REQUISITIONER_CONTACTS.length };
}

export function findRequisitionerContact(name: string) {
  const key = String(name || "").trim().toLowerCase().replace(/\s+/g, " ");
  if (!key) return undefined;
  return (
    REQUISITIONER_CONTACTS.find(
      (contact) => contact.name.trim().toLowerCase().replace(/\s+/g, " ") === key,
    ) ||
    REQUISITIONER_CONTACTS.find((contact) => {
      const candidate = contact.name.trim().toLowerCase().replace(/\s+/g, " ");
      return candidate.includes(key) || key.includes(candidate);
    })
  );
}

export function searchRequisitionerContacts(query: string, limit = 50) {
  const q = String(query || "").trim().toLowerCase();
  const matches = !q
    ? REQUISITIONER_CONTACTS
    : REQUISITIONER_CONTACTS.filter(
        (contact) =>
          contact.name.toLowerCase().includes(q) ||
          contact.email.toLowerCase().includes(q),
      );
  return matches.slice(0, Math.max(1, limit));
}
